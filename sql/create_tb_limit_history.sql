/*
    Audit tables for runtime-limit changes (components + rollers).
    Populated only on future limit edits — no backfill of past changes.
*/

USE SFC_WR_DB;
GO

IF OBJECT_ID(N'dbo.TB_COMPONENTS_LIMIT_HISTORY', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_COMPONENTS_LIMIT_HISTORY (
        HIST_ID            BIGINT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_TB_COMPONENTS_LIMIT_HISTORY PRIMARY KEY,
        PART_ID            VARCHAR(20)     NOT NULL,
        MACHINE_NM         NVARCHAR(100)   NULL,
        PART_TYPE          NVARCHAR(100)   NULL,
        PART_SEQ           INT             NULL,
        OLD_LIMIT_HOUR     DECIMAL(12, 2)  NULL,
        NEW_LIMIT_HOUR     DECIMAL(12, 2)  NOT NULL,
        CHANGED_DT         DATETIME2(0)    NOT NULL CONSTRAINT DF_TB_COMPONENTS_LIMIT_HISTORY_DT DEFAULT (SYSUTCDATETIME()),
        CHANGED_BY         NVARCHAR(100)   NULL
    );

    CREATE INDEX IX_TB_COMPONENTS_LIMIT_HISTORY_PART
        ON dbo.TB_COMPONENTS_LIMIT_HISTORY (PART_ID, CHANGED_DT DESC);
END;
GO

IF OBJECT_ID(N'dbo.TB_ROLLER_LIMIT_HISTORY', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.TB_ROLLER_LIMIT_HISTORY (
        HIST_ID            BIGINT IDENTITY(1, 1) NOT NULL CONSTRAINT PK_TB_ROLLER_LIMIT_HISTORY PRIMARY KEY,
        ROLLER_ID          VARCHAR(30)     NOT NULL,
        BIN_LOCATION_CD    VARCHAR(50)     NULL,
        OLD_LIMIT_HOUR     DECIMAL(12, 2)  NULL,
        NEW_LIMIT_HOUR     DECIMAL(12, 2)  NOT NULL,
        CHANGED_DT         DATETIME2(0)    NOT NULL CONSTRAINT DF_TB_ROLLER_LIMIT_HISTORY_DT DEFAULT (SYSUTCDATETIME()),
        CHANGED_BY         NVARCHAR(100)   NULL
    );

    CREATE INDEX IX_TB_ROLLER_LIMIT_HISTORY_ROLLER
        ON dbo.TB_ROLLER_LIMIT_HISTORY (ROLLER_ID, CHANGED_DT DESC);

    CREATE INDEX IX_TB_ROLLER_LIMIT_HISTORY_BIN
        ON dbo.TB_ROLLER_LIMIT_HISTORY (BIN_LOCATION_CD, CHANGED_DT DESC);
END;
GO
